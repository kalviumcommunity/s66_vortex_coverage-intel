"""Vector Repository — Data Access Object (DAO) for Pinecone Vector Database.

Handles index operations, batch vector upserts, and similarity searches using
the injected Pinecone client connection.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from typing import Any

from pinecone import Pinecone

from ..exceptions import PineconeConnectionError, VectorRepositoryError
from ..models import DocumentChunk, ScoredRecord

logger = logging.getLogger("coverage-intel.rag.repository")


class VectorRepository:
    """Repository managing direct vector mutations and similarity queries in Pinecone."""

    def __init__(
        self,
        pinecone_client: Pinecone,
        index_name: str,
    ) -> None:
        """Initialize the VectorRepository with an injected Pinecone client connection.

        Args:
            pinecone_client: Shared Pinecone client connection.
            index_name: Target Pinecone index name.
        """
        self._client = pinecone_client
        self._index_name = index_name
        self._index: Any = None

    @property
    def index_name(self) -> str:
        """Return the target index name."""
        return self._index_name

    def _get_index(self) -> Any:
        """Lazy-load and return the connected Pinecone Index handle."""
        if self._index is None:
            try:
                logger.debug("Connecting to Pinecone index '%s'", self._index_name)
                self._index = self._client.Index(self._index_name)
            except Exception as exc:
                logger.error("Failed to connect to Pinecone index '%s': %s", self._index_name, exc)
                raise PineconeConnectionError(
                    f"Unable to access Pinecone index '{self._index_name}': {exc}"
                ) from exc
        return self._index

    def upsert_chunks(
        self,
        chunks: Sequence[DocumentChunk],
        embeddings: Sequence[Sequence[float]],
        namespace: str = "",
        batch_size: int = 100,
    ) -> int:
        """Upsert a sequence of document chunks with their corresponding vectors into Pinecone.

        Args:
            chunks: DocumentChunk domain records.
            embeddings: Corresponding float vector arrays generated by EmbeddingService.
            namespace: Optional Pinecone namespace.
            batch_size: Batch size for network payloads.

        Returns:
            Total count of upserted vector records.

        Raises:
            VectorRepositoryError: If the index mutation fails.
        """
        if len(chunks) != len(embeddings):
            raise VectorRepositoryError(
                f"Mismatch: received {len(chunks)} chunks and {len(embeddings)} embedding vectors.",
                retryable=False,
            )
        if not chunks:
            return 0

        index = self._get_index()
        total_upserted = 0

        try:
            for i in range(0, len(chunks), batch_size):
                batch_chunks = chunks[i : i + batch_size]
                batch_vectors = embeddings[i : i + batch_size]

                records_to_upsert: list[dict[str, Any]] = []
                for chunk, vector in zip(batch_chunks, batch_vectors, strict=True):
                    clean_meta: dict[str, Any] = {}
                    for k, v in dict(chunk.metadata).items():
                        if v is not None:
                            if hasattr(v, "isoformat"):
                                clean_meta[k] = v.isoformat()
                            elif isinstance(v, (str, int, float, bool, list)):
                                clean_meta[k] = v
                    clean_meta["text"] = chunk.text or ""
                    clean_meta["document_id"] = chunk.document_id or ""

                    records_to_upsert.append(
                        {
                            "id": chunk.id,
                            "values": list(vector),
                            "metadata": clean_meta,
                        }
                    )

                logger.debug(
                    "Upserting batch of %d vectors into Pinecone index '%s' (namespace='%s')",
                    len(records_to_upsert),
                    self._index_name,
                    namespace,
                )
                index.upsert(vectors=records_to_upsert, namespace=namespace)
                total_upserted += len(records_to_upsert)

            logger.info("Successfully upserted %d total vectors to index '%s'", total_upserted, self._index_name)
            return total_upserted

        except Exception as exc:
            logger.error("Failed to upsert vectors into Pinecone: %s", exc, exc_info=True)
            raise VectorRepositoryError(f"Vector upsert failed on index '{self._index_name}': {exc}", retryable=True) from exc

    def query_similar(
        self,
        vector: list[float],
        top_k: int = 5,
        filter_dict: dict[str, Any] | None = None,
        namespace: str = "",
    ) -> list[ScoredRecord]:
        """Perform a vector similarity query against Pinecone.

        Args:
            vector: Query embedding generated by EmbeddingService.
            top_k: Number of nearest neighbors to return.
            filter_dict: Optional metadata filter expression (Pinecone filter syntax).
            namespace: Optional Pinecone namespace.

        Returns:
            List of ScoredRecord domain items sorted by relevance score descending.

        Raises:
            VectorRepositoryError: If the query fails.
        """
        if not vector:
            raise VectorRepositoryError("Query vector cannot be empty.", retryable=False)

        index = self._get_index()

        try:
            logger.debug(
                "Querying Pinecone index '%s' (top_k=%d, filter=%s, namespace='%s')",
                self._index_name,
                top_k,
                filter_dict,
                namespace,
            )
            response: Any = index.query(
                vector=vector,
                top_k=top_k,
                include_metadata=True,
                filter=filter_dict,
                namespace=namespace,
            )

            results: list[ScoredRecord] = []
            matches = getattr(response, "matches", []) or []

            for match in matches:
                match_id = getattr(match, "id", "")
                score = float(getattr(match, "score", 0.0))
                raw_meta = getattr(match, "metadata", {}) or {}

                text = raw_meta.get("text", "")
                doc_id = raw_meta.get("document_id", "")

                # Clean text out of generic metadata to keep clean model
                meta_clean = {k: v for k, v in raw_meta.items() if k not in {"text"}}

                results.append(
                    ScoredRecord(
                        id=match_id,
                        score=score,
                        text=text,
                        document_id=doc_id,
                        metadata=meta_clean,
                    )
                )

            return results

        except Exception as exc:
            logger.error("Pinecone query execution failed: %s", exc, exc_info=True)
            raise VectorRepositoryError(f"Vector query failed on index '{self._index_name}': {exc}", retryable=True) from exc

    def delete_by_document(self, document_id: str, namespace: str = "") -> None:
        """Delete all vectors associated with a specific document identifier."""
        if not document_id:
            return

        index = self._get_index()
        try:
            logger.info("Deleting vectors for document_id '%s' from index '%s'", document_id, self._index_name)
            index.delete(filter={"document_id": {"$eq": document_id}}, namespace=namespace)
        except Exception as exc:
            logger.error("Failed to delete vectors for document_id '%s': %s", document_id, exc)
            raise VectorRepositoryError(f"Failed to delete document vectors: {exc}") from exc

    def describe_index_stats(self) -> dict[str, Any]:
        """Fetch index statistics (total vector count, dimension, namespaces)."""
        index = self._get_index()
        try:
            stats = index.describe_index_stats()
            return stats.to_dict() if hasattr(stats, "to_dict") else dict(stats)
        except Exception as exc:
            raise VectorRepositoryError(f"Failed to retrieve index stats: {exc}") from exc

    query_similarity = query_similar

